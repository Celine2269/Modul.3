# Lage variabler
navn = "Celine"
alder = 24
hoyde = 1.70
er_student = True
hobbyer = ["Tur", "Serier", "Puslespill"]

# Print i riktig rekkefølge
print("Navn:", navn)
print("Alder:", alder)
print("Høyde:", hoyde)
print("Er student:", er_student)
print("Hobbyer:", hobbyer)

# Print i motsatt rekkefølge
print("Hobbyer:", hobbyer)
print("Er student:", er_student)
print("Høyde:", hoyde)
print("Alder:", alder)
print("Navn:", navn)

# Print type av variablene
print(type(navn)) 
print(type(alder))
print(type(hoyde))
print(type(er_student))
print(type(hobbyer))

